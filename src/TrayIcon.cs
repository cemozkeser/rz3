    // The tray "logo": a small mouse with a green wheel, plus - if the user wants it - a battery
    // level bar. Drawn at several sizes and packed into a real multi-size .ico so Windows can use
    // the 16 px version in the tray and the 32/48 px one in menus and Alt-Tab.
    public static class TrayIconFactory
    {
        static readonly Color Ink = Color.FromArgb(38, 40, 44);
        static readonly Color Paper = Color.FromArgb(238, 240, 243);
        static readonly Color Accent = Color.FromArgb(68, 214, 44);     // Razer green

        // Windows asks for 16 px in the tray and 32/48 px in menus, so the .ico carries all four.
        // The frames are written as classic DIB (BITMAPINFOHEADER) entries, NOT PNG: .NET
        // Framework 4.8 parses PNG-compressed icon entries just far enough to report a size, and
        // then throws ArgumentOutOfRangeException from Icon.ToBitmap() - the tray falls back to a
        // blank/placeholder icon. Measured with tools6/IcoTry.exe: PNG entries fail, DIB entries
        // round-trip at every size.
        public static Icon Build(bool showBattery, int battery, bool charging)
        {
            int[] sizes = new int[] { 16, 24, 32, 48 };
            List<byte[]> frames = new List<byte[]>();
            foreach (int s in sizes)
            {
                using (Bitmap bmp = Render(s, showBattery, battery, charging))
                    frames.Add(DibFrame(bmp));
            }
            return FromFrames(sizes, frames);
        }

        // The tray artwork is also the application icon: it is embedded in the exe at build time
        // (Rz3.ico, generated by tools9/MakeIcon.exe) so the taskbar, Alt-Tab and Explorer show the
        // same logo the tray does. This exposes the same drawing for the in-app window icon.
        public static Icon AppIcon()
        {
            try
            {
                string ico = Path.Combine(Application.StartupPath, "Rz3.ico");
                if (File.Exists(ico)) return new Icon(ico, 32, 32);
            }
            catch { }
            return Build(false, -1, false);
        }

        // One 32bpp ICO frame: BITMAPINFOHEADER (height doubled), BGRA rows bottom-up, then the
        // 1-bit AND mask with 32-bit padded rows.
        static byte[] DibFrame(Bitmap art)
        {
            int w = art.Width, h = art.Height;
            using (MemoryStream ms = new MemoryStream())
            using (BinaryWriter bw = new BinaryWriter(ms))
            {
                bw.Write(40);              // biSize
                bw.Write(w);               // biWidth
                bw.Write(h * 2);           // biHeight = XOR + AND
                bw.Write((short)1);        // biPlanes
                bw.Write((short)32);       // biBitCount
                bw.Write(0);               // biCompression = BI_RGB
                bw.Write(0);               // biSizeImage
                bw.Write(0); bw.Write(0);  // pixels per meter
                bw.Write(0); bw.Write(0);  // clrUsed / clrImportant

                for (int y = h - 1; y >= 0; y--)
                    for (int x = 0; x < w; x++)
                    {
                        Color c = art.GetPixel(x, y);
                        bw.Write(c.B); bw.Write(c.G); bw.Write(c.R); bw.Write(c.A);
                    }

                int maskStride = ((w + 31) / 32) * 4;
                for (int y = h - 1; y >= 0; y--)
                {
                    byte[] row = new byte[maskStride];
                    for (int x = 0; x < w; x++)
                        if (art.GetPixel(x, y).A < 128)
                            row[x / 8] |= (byte)(0x80 >> (x % 8));
                    bw.Write(row);
                }
                bw.Flush();
                return ms.ToArray();
            }
        }

        // Public so --icontest can dump the artwork and check it is not blank.
        public static Bitmap Render(int size, bool showBattery, int battery, bool charging)
        {
            Bitmap bmp = new Bitmap(size, size, PixelFormat.Format32bppArgb);
            using (Graphics g = Graphics.FromImage(bmp))
            {
                g.SmoothingMode = SmoothingMode.AntiAlias;
                g.InterpolationMode = InterpolationMode.HighQualityBicubic;
                g.Clear(Color.Transparent);
                float u = size / 16f;                     // one design unit
                bool big = size >= 24;

                // body of the mouse
                RectangleF body = new RectangleF(4f * u, 1.5f * u, 8f * u, 12.5f * u);
                using (GraphicsPath path = Rounded(body, 4f * u))
                {
                    using (SolidBrush b = new SolidBrush(Ink)) g.FillPath(b, path);
                    if (big)
                    {
                        using (Pen p = new Pen(Paper, Math.Max(1f, 0.55f * u)))
                            g.DrawPath(p, path);
                    }
                }
                // button split and wheel
                using (Pen split = new Pen(Paper, Math.Max(1f, 0.5f * u)))
                {
                    if (big) g.DrawLine(split, 8f * u, 2f * u, 8f * u, 4.6f * u);
                }
                using (SolidBrush wheel = new SolidBrush(Accent))
                    g.FillRectangle(wheel, 7.2f * u, 5.4f * u, 1.6f * u, big ? 2.6f * u : 2.2f * u);

                if (!showBattery || battery < 0) return bmp;

                // battery: shell + level, sitting in the lower right corner
                float bw = big ? 9f * u : 8f * u;
                float bh = big ? 4.4f * u : 4f * u;
                RectangleF shell = new RectangleF(size - bw - 0.6f * u, size - bh - 0.6f * u, bw, bh);
                using (SolidBrush back = new SolidBrush(Color.FromArgb(230, 250, 250, 250)))
                    g.FillRectangle(back, shell);
                using (Pen outline = new Pen(Ink, Math.Max(1f, 0.5f * u)))
                    g.DrawRectangle(outline, shell.X, shell.Y, shell.Width, shell.Height);
                using (Pen nub = new Pen(Ink, Math.Max(1f, 0.5f * u)))
                    g.DrawLine(nub, shell.Right, shell.Y + shell.Height * 0.3f, shell.Right, shell.Bottom - shell.Height * 0.3f);

                int level = Math.Max(0, Math.Min(100, battery));
                Color fill = charging ? Color.FromArgb(64, 156, 255)
                    : level > 50 ? Accent
                    : level > 20 ? Color.FromArgb(240, 190, 40)
                    : Color.FromArgb(230, 72, 62);
                float innerW = Math.Max(0, (shell.Width - 2f * u) * level / 100f);
                if (innerW > 0.4f * u)
                {
                    using (SolidBrush fb = new SolidBrush(fill))
                        g.FillRectangle(fb, shell.X + 0.6f * u, shell.Y + 0.6f * u, innerW, Math.Max(1f, shell.Height - 1.2f * u));
                }
            }
            return bmp;
        }

        static GraphicsPath Rounded(RectangleF r, float radius)
        {
            GraphicsPath p = new GraphicsPath();
            float d = radius * 2f;
            if (d > r.Width) d = r.Width;
            if (d > r.Height) d = r.Height;
            p.AddArc(r.X, r.Y, d, d, 180, 90);
            p.AddArc(r.Right - d, r.Y, d, d, 270, 90);
            p.AddArc(r.Right - d, r.Bottom - d, d, d, 0, 90);
            p.AddArc(r.X, r.Bottom - d, d, d, 90, 90);
            p.CloseFigure();
            return p;
        }

        // Minimal ICO writer (classic DIB entries, see the note on Build).
        static MemoryStream _stream;      // the tray keeps the newest icon; older icons are disposed

        static Icon FromFrames(int[] sizes, List<byte[]> frames)
        {
            MemoryStream ms = new MemoryStream();
            using (BinaryWriter w = new BinaryWriter(ms, System.Text.Encoding.UTF8, true))
            {
                w.Write((short)0);              // reserved
                w.Write((short)1);              // type: icon
                w.Write((short)sizes.Length);   // image count
                int offset = 6 + 16 * sizes.Length;
                for (int i = 0; i < sizes.Length; i++)
                {
                    int s = sizes[i];
                    w.Write((byte)(s >= 256 ? 0 : s));
                    w.Write((byte)(s >= 256 ? 0 : s));
                    w.Write((byte)0);           // palette
                    w.Write((byte)0);           // reserved
                    w.Write((short)1);          // planes
                    w.Write((short)32);         // bpp
                    w.Write(frames[i].Length);
                    w.Write(offset);
                    offset += frames[i].Length;
                }
                foreach (byte[] f in frames) w.Write(f);
                w.Flush();
                ms.Position = 0;
            }
            _stream = ms;                 // Icon parses from the stream; one live copy is enough
            // 16x16 is the tray size: asking for it makes Windows pick that frame for the
            // notification area and keep the larger ones for menus.
            return new Icon(ms, 16, 16);
        }
    }

    // Tiny key/value settings store for UI preferences (the action table lives in rz3_host.json).
    public static class UiPrefs
    {
        static string FilePath
        {
            get { return Path.Combine(Application.StartupPath, "rz3_ui.json"); }
        }

        static Dictionary<string, string> Read()
        {
            Dictionary<string, string> map = new Dictionary<string, string>();
            try
            {
                if (!File.Exists(FilePath)) return map;
                foreach (string line in File.ReadAllLines(FilePath))
                {
                    int eq = line.IndexOf('=');
                    if (eq <= 0) continue;
                    map[line.Substring(0, eq).Trim()] = line.Substring(eq + 1).Trim();
                }
            }
            catch { }
            return map;
        }

        public static bool GetBool(string key, bool fallback)
        {
            string v;
            if (!Read().TryGetValue(key, out v)) return fallback;
            return v == "1" || v.Equals("true", StringComparison.OrdinalIgnoreCase);
        }

        public static void SetBool(string key, bool value)
        {
            try
            {
                Dictionary<string, string> map = Read();
                map[key] = value ? "1" : "0";
                Write(map);
            }
            catch { }
        }

        public static void Remove(string key)
        {
            try
            {
                Dictionary<string, string> map = Read();
                if (!map.Remove(key)) return;
                Write(map);
            }
            catch { }
        }

        static void Write(Dictionary<string, string> map)
        {
            List<string> keys = new List<string>(map.Keys);
            keys.Sort();
            System.Text.StringBuilder sb = new System.Text.StringBuilder();
            sb.AppendLine("# Rz3 UI preferences");
            foreach (string k in keys) sb.AppendLine(k + "=" + map[k]);
            File.WriteAllText(FilePath, sb.ToString(), System.Text.Encoding.UTF8);
        }
    }
